import { Schema } from "effect";

import {
  ENVIRONMENT_ONLY_SETTINGS,
  SETTING_ENV_BY_KEY,
  SETTINGS_FILE,
  SettingsFile,
} from "../services/settings.ts";

/**
 * The published JSON Schema and the Settings reference, both rendered from
 * the Effect Schema that decodes `config.json` (ADR 0063). The build writes
 * them; a test fails when the committed copies drift.
 */

export const SETTINGS_REFERENCE_FILE = "docs/settings.md";

interface JsonSchemaNode {
  readonly default?: unknown;
  readonly description?: string;
  readonly enum?: readonly unknown[];
  readonly maximum?: number;
  readonly minimum?: number;
  readonly properties?: Readonly<Record<string, JsonSchemaNode>>;
  readonly type?: string;
}

const settingsDocument = () =>
  Schema.toJsonSchemaDocument(SettingsFile, { onExcessProperty: "error" });

export const renderSettingsJsonSchema = (): string => {
  const document = settingsDocument();
  const definitions =
    Object.keys(document.definitions).length > 0
      ? { $defs: document.definitions }
      : {};
  return `${JSON.stringify(
    {
      $schema: "https://json-schema.org/draft/2020-12/schema",
      ...document.schema,
      ...definitions,
    },
    null,
    2
  )}\n`;
};

const typeOf = (node: JsonSchemaNode): string => {
  if (node.enum !== undefined) {
    return node.enum
      .map((value) => `\`${JSON.stringify(value)}\``)
      .join(" or ");
  }
  const range =
    node.minimum !== undefined && node.maximum !== undefined
      ? ` (${node.minimum}–${node.maximum})`
      : "";
  return `${node.type ?? "any"}${range}`;
};

const cell = (text: string) => text.replaceAll("|", "\\|");

export const renderSettingsReference = (): string => {
  const document = settingsDocument();
  // SAFETY: the document is the JSON Schema rendered from `SettingsFile`, an
  // object whose sections are objects of scalar properties.
  const root = document.schema as JsonSchemaNode;
  const sections = Object.entries(root.properties ?? {}).filter(
    ([name]) => name !== "$schema"
  );
  const lines = [
    "<!-- Generated by src/packaging/generate-settings.ts from the Settings schema. Do not edit. -->",
    "",
    "# Settings",
    "",
    "A Setting is a choice about how Contingency itself runs, such as which port to serve on. Set it in a `config.json` file or in its environment variable.",
    "",
    "## Where Contingency reads Settings",
    "",
    `Contingency reads \`${SETTINGS_FILE}\` from two places:`,
    "",
    `- The project file, \`${SETTINGS_FILE}\` in the Catalog Root. The Catalog Root is \`.contingency\` in the project directory, or \`CONTINGENCY_CATALOG_ROOT\` when it is set.`,
    `- The user file, \`~/.contingency/${SETTINGS_FILE}\`.`,
    "",
    "Both files use one schema. For each Setting, the first source that names it wins:",
    "",
    "1. A command-line flag.",
    "2. The environment variable.",
    "3. The project file.",
    "4. The user file.",
    "5. The default.",
    "",
    "`contingency start` and agents registered with `contingency register` start the MCP server with `CONTINGENCY_MCP_PORT=0`, so concurrent sessions never compete for one port. A file's `mcp.port` applies only when you run `contingency mcp` yourself.",
    "",
    "## Create a file",
    "",
    "Run `contingency config init`. It writes a project file that holds only `$schema`, pinned to the installed CLI version, so an editor completes and checks each key. It never overwrites an existing file.",
    "",
    "If `$schema` names a different CLI version, Contingency prints a one-line warning at startup and validates the file against its own schema.",
    "",
    "## Validation",
    "",
    "Validation is strict. An unknown key, a value of the wrong type, or an environment-only key stops startup. The error names the file and the JSON pointer of each problem, for example `/mcp/port: Expected number`.",
    "",
  ];
  for (const [section, node] of sections) {
    lines.push(
      `## \`${section}\``,
      "",
      node.description ?? "",
      "",
      "| Key | Environment variable | Type | Default | Description |",
      "| --- | --- | --- | --- | --- |"
    );
    for (const [key, property] of Object.entries(node.properties ?? {})) {
      lines.push(
        `| \`${section}.${key}\` | \`${SETTING_ENV_BY_KEY.get(`${section}.${key}`) ?? ""}\` | ${cell(typeOf(property))} | ${property.default === undefined ? "—" : `\`${JSON.stringify(property.default)}\``} | ${cell(property.description ?? "")} |`
      );
    }
    lines.push("");
  }
  lines.push(
    "## Environment-only Settings",
    "",
    "These Settings are read only from the environment. A file that contains one fails validation: a secret must not be committed, and a file cannot say where it lives.",
    "",
    "| Environment variable | Rejected file key |",
    "| --- | --- |",
    ...ENVIRONMENT_ONLY_SETTINGS.map(
      ({ env, key }) => `| \`${env}\` | \`${key}\` |`
    ),
    "",
    "A Variable value, such as a password a Flow Skill uses, is never a Setting. Supply Variable values when a Run asks for them; see [Variables](./variables.md).",
    ""
  );
  return lines.join("\n");
};
